// Existing workbook: PRODUCTS (A–I + the optional keyword column the operator added), an operator note
// column, a second product, and an MVP-era REELS sheet.
function workbook() {
  const env = createEnv({ gemini: () => plain(env.gs('FIXTURE_PRD_001_GEMINI_RESPONSE')) });
  env.sheets.PRODUCTS = new MockSheet('PRODUCTS', [
    PRODUCT_HEADERS.concat(['ManyChat 키워드', '운영자 메모']),
    prd001Row(env.gs, { permission: '자체 제작', affiliateUrl: 'https://link.coupang.com/a/umbrella' }).concat(['우산', '현관용']),
    ['PRD-002', '다른 상품', '', '확인된 기능 하나', '', '', '', '미확인', '', '타일', ''],
  ]);
  env.gs('setupSheets()');
  const call = (fn, ...a) => plain(env.gs(fn).apply(null, a));
  const act = (reelId, name, input = {}) => {
    const d = call('apiGetReel', reelId).detail;
    return call('apiAction', reelId, name, Object.assign({ expectedStatus: d.summary.status, expectedScriptVersion: d.summary.scriptVersion, expectedVideoVersion: d.summary.videoVersion }, input));
  };
  return { env, call, act };
}
function ttsService(dir, provider) {
  return createTtsService({ provider, voice: 'ko-KR-Wavenet-A', speakingRate: 1, cacheDir: path.join(dir, 'cache'), ledgerFile: path.join(dir, 'usage.json') });
}
function paidSpy() {
  const inner = createSilentTts();
  return { name: 'paid-spy', paid: true, calls: inner.calls, synthesize: inner.synthesize };
}

test('1. existing Google Sheets data is preserved', () => {
  const { env, call } = workbook();
  const before = JSON.stringify(env.sheets.PRODUCTS.rows);
  call('apiGenerateScripts', 'PRD-001');
  call('apiGetDashboard');
  assert.equal(JSON.stringify(env.sheets.PRODUCTS.rows), before, 'PRODUCTS (incl. operator columns) never written');
  // MVP-era REELS rows and operator columns survive 시트 준비 and approvals (see webapp.test.js for the full migration).
  assert.ok(env.sheets.REELS.rows[0].includes('Flow 장면 프롬프트'));
});

test('2–3. script approval works, and Flow prompts appear only after approval', () => {
  const { env, call, act } = workbook();
  const gen = call('apiGenerateScripts', 'PRD-001');
  assert.deepEqual(gen.ids, ['PRD-001-R01']);
  const rec = () => env.sheets.REELS.record(env.sheets.REELS.rows.findIndex((r) => r[0] === 'PRD-001-R01') + 1);
  assert.equal(rec()['ManyChat 키워드'], '우산', 'product keyword used for every PRD-001 reel');
  assert.equal(rec()['Flow 장면 프롬프트'], '', 'no Flow prompts before approval');
  assert.deepEqual(call('apiGetReel', 'PRD-001-R01').detail.flowScenePrompts, []);

  const ap = act('PRD-001-R01', 'APPROVE_SCRIPT');
  assert.equal(ap.detail.summary.status, 'SCRIPT_APPROVED');
  const prompts = ap.detail.flowScenePrompts;
  assert.equal(prompts.length, 6, 'one Flow prompt per scene');
  const p = prompts[1].prompt;
  for (const k of ['PRODUCT (identical in every scene): 리템 우산꽂이 자석형', '주 색상 다크그레이', '190×55×50mm', 'SCENE:', 'PRODUCT INTERACTION:', 'CAMERA:', 'LIGHTING & ENVIRONMENT:', 'DURATION: 8 seconds', 'CONSISTENCY:']) {
    assert.ok(p.includes(k), k);
  }
  assert.doesNotMatch(prompts.map((x) => x.prompt).join('\n'), /link\.coupang|우산꽂이 최저가|100%/);
  assert.equal(env.state.fetches.length, 1, 'prompts are generated by code — no extra Gemini call');

  // Changing the approved script removes the prompts (no Flow credits on an unapproved script).
  const re = act('PRD-001-R01', 'REOPEN_SCRIPT');
  assert.deepEqual(re.detail.flowScenePrompts, []);
});

test('product keywords: shared by one product, never reused by another product', () => {
  const { env, call } = workbook();
  call('apiGenerateScripts', 'PRD-001');
  // A second batch needs five new hooks (repeating this product's hooks is refused); same keyword is fine.
  env.gs(`(function () {
    const f = FIXTURE_PRD_001_GEMINI_RESPONSE;
    ['장마철마다 현관 정리 포기한 사람?', '두 조각으로 나눠 붙이는 이유', '젖은 우산, 꼭 바닥에 둘 필요 없어요', '아침마다 우산 어디 뒀는지 헷갈려요', '현관 우산은 문에 두면 돼요']
      .forEach(function (t, i) { f.hooks[i].text = t; });
    const r = f.reels[0];
    r.hook = f.hooks[3].text; r.scenes[0].narration = r.hook; r.captions[0] = r.hook;
  })()`);
  const more = call('apiGenerateScripts', 'PRD-001', true);
  assert.equal(more.ok, true, 'a second batch for the same product may reuse 우산');
  env.sheets.PRODUCTS.set(3, 'ManyChat 키워드', '우산');
  const calls = env.state.fetches.length;
  const clash = call('apiGenerateScripts', 'PRD-002');
  assert.equal(clash.ok, false);
  assert.match(clash.error, /우산.*다른 릴스·상품\(PRD-001\)/);
  assert.equal(env.state.fetches.length, calls, 'refused before any Gemini call');
  env.sheets.PRODUCTS.set(3, 'ManyChat 키워드', '우 산');
  assert.match(call('apiGenerateScripts', 'PRD-002').error, /공백·따옴표 없이 20자 이내/);
});

test('4–5. missing footage stops rendering; TTS only after approval', { skip: !hasFfmpeg && 'FFmpeg not installed' }, async () => {
  const { env, call, act } = workbook();
  call('apiGenerateScripts', 'PRD-001');
  // No render job before approval.
  assert.match(call('apiGetRenderJob', 'PRD-001-R01').error, /영상 제작 중/);
  act('PRD-001-R01', 'APPROVE_SCRIPT');
  assert.match(call('apiGetRenderJob', 'PRD-001-R01').error, /영상 제작 중/, 'approved but not started → still no job');
  act('PRD-001-R01', 'START_VIDEO');
  const jobFile = JSON.parse(call('apiGetRenderJob', 'PRD-001-R01').jobFile);
  const secret = env.props.RF_RENDER_SECRET;
  const dir = tmp();
  const provider = paidSpy();
  const opts = { jobFile, secret, template: loadTemplate(), tts: ttsService(dir, provider), storage: createLocalStorage({ outputDir: path.join(dir, 'out') }), clipsDir: path.join(dir, 'clips'), ffmpeg: FF, font: 'NanumGothic', preset: 'ultrafast', crf: 36 };

  // A forged "approved" job (wrong key) and an unapproved script are refused before any TTS.
  const q = JSON.parse(jobFile.payload);
  q.status = 'SCRIPT_REVIEW_PENDING';
  const forged = JSON.stringify(q);
  await assert.rejects(render(Object.assign({}, opts, { jobFile: { payload: forged, signature: sign(forged, 'not-the-key') } })), GateError);
  await assert.rejects(render(Object.assign({}, opts, { jobFile: { payload: forged, signature: sign(forged, secret) } })), /영상 제작 중/);
  // No footage → ASSETS_REQUIRED, still no TTS.
  await assert.rejects(render(opts), AssetsRequiredError);
  assert.equal(provider.calls.length, 0, 'zero paid TTS calls so far');
  assert.ok(fs.existsSync(path.join(dir, 'clips', 'PRD-001-R01', 'FLOW_PROMPTS.md')));
});

test('6–7. full flow: Flow clips → render → final video approval → manual publishing only', { skip: !hasFfmpeg && 'FFmpeg not installed' }, async () => {
  const { env, call, act } = workbook();
  call('apiGenerateScripts', 'PRD-001');
  act('PRD-001-R01', 'APPROVE_SCRIPT');
  act('PRD-001-R01', 'START_VIDEO');
  const jobFile = JSON.parse(call('apiGetRenderJob', 'PRD-001-R01').jobFile);
  assert.equal(verifyJob(jobFile, { secret: env.props.RF_RENDER_SECRET }).flowPrompts.length, 6);

  // Operator uploads one Flow clip per scene (synthetic stand-ins here).
  const dir = tmp();
  const clipDir = path.join(dir, 'clips', 'PRD-001-R01');
  fs.mkdirSync(clipDir, { recursive: true });
  for (let n = 1; n <= 6; n++) {
    execFileSync('ffmpeg', ['-v', 'error', '-y', '-f', 'lavfi', '-i', 'testsrc2=s=720x1280:d=8:r=30', '-c:v', 'libx264', '-preset', 'ultrafast', '-pix_fmt', 'yuv420p', path.join(clipDir, `S${n}.mp4`)]);
  }
  const provider = paidSpy();
  const m = await render({ jobFile, secret: env.props.RF_RENDER_SECRET, template: loadTemplate(), tts: ttsService(dir, provider), storage: createLocalStorage({ outputDir: path.join(dir, 'out') }), clipsDir: path.join(dir, 'clips'), ffmpeg: FF, font: 'NanumGothic', preset: 'ultrafast', crf: 36 });
  assert.equal(m.qc.postRender.ok, true);
  assert.equal(provider.calls.length, 6, 'TTS once per scene line, only after approval + footage');
  assert.deepEqual(m.timeline.beats.map((b) => b.subtitle.join(' ')), ['비 오는 날, 현관에 젖은 우산이 굴러다녀요', '신발 둘 자리도 모자라잖아요', '자석이라 철제 현관문에 붙이면 돼요', '긴 우산도 접는 우산도 쏙 꽂아요', '위아래 두 조각으로 나뉘어 있어요', "저장해 두고, 댓글에 '우산' 남겨 주세요"]);

  // Operator uploads the MP4 to Drive and registers it; reviews on iPhone.
  const reg = act('PRD-001-R01', 'REGISTER_VIDEO', { videoUrl: 'https://drive.google.com/file/d/1AbCdEfGhIjKlMnOpQrStUvWxYz012345/view' });
  assert.equal(reg.detail.summary.status, 'VIDEO_REVIEW_PENDING');
  const av = act('PRD-001-R01', 'APPROVE_VIDEO');
  assert.equal(av.detail.summary.status, 'READY_TO_PUBLISH', 'final video approval works');

  // Nothing is published automatically: the system only hands over a pack and waits for confirmations.
  const pack = call('apiGetPublishingPack', 'PRD-001-R01').pack;
  assert.ok(pack.instagramCaption.startsWith('[광고] 이 게시물은 쿠팡 파트너스 활동의 일환으로'));
  assert.equal(pack.manychatKeyword, '우산');
  assert.ok(pack.checklist.some((c) => /AI 정보/.test(c)));
  assert.equal(call('apiGetReel', 'PRD-001-R01').detail.summary.status, 'READY_TO_PUBLISH', 'still waiting for the operator');
  act('PRD-001-R01', 'CONFIRM_PUBLISHED');
  assert.equal(act('PRD-001-R01', 'CONFIRM_MANYCHAT').detail.summary.status, 'COMPLETED');
  const outbound = env.state.fetches.length;
  assert.equal(outbound, 1, 'the only outbound call in the whole flow was the one Gemini script request');
});

test('7. no code path can publish to Instagram or configure ManyChat', () => {
  const root = path.join(__dirname, '..');
  const files = []
    .concat(fs.readdirSync(path.join(root, 'apps-script')).map((f) => path.join(root, 'apps-script', f)))
    .concat(['cli.js'].map((f) => path.join(root, 'renderer', f)))
    .concat(fs.readdirSync(path.join(root, 'renderer', 'lib'), { recursive: true }).filter((f) => f.endsWith('.js')).map((f) => path.join(root, 'renderer', 'lib', f)));
  const code = files.map((f) => fs.readFileSync(f, 'utf8')).join('\n');
  assert.doesNotMatch(code, /graph\.facebook\.com|graph\.instagram\.com|api\.instagram\.com|manychat\.com\/fb|api\.manychat/i);
  // Every network endpoint the code can call:
  const urls = [...code.matchAll(/https?:\/\/[a-z0-9.\-]+/gi)].map((m) => m[0].toLowerCase());
  const calledHosts = new Set(urls.filter((u) => /googleapis\.com|metadata\.google\.internal/.test(u)));
  assert.deepEqual([...calledHosts].sort(), [
    'http://metadata.google.internal',
    'https://generativelanguage.googleapis.com',
    'https://texttospeech.googleapis.com',
    'https://www.googleapis.com',
  ].filter((h) => calledHosts.has(h)).sort());
  assert.ok(!calledHosts.has('https://www.googleapis.com') || /oauth/.test(code), 'only OAuth scope strings use www.googleapis.com');
});
